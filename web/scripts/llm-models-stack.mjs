// Real browser, application and PostgreSQL; fake only the external model service.
import { chromium, expect } from "@playwright/test";
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const base = process.env.VOICES_TEST_URL;
const remote = process.env.VOICES_MODEL_TEST_URL;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: "dark" });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(base);
  await page.getByLabel("邮箱", { exact: true }).fill("models-admin@example.test");
  await page.getByLabel("用户名", { exact: true }).fill("ModelsAdmin");
  await page.getByLabel("密码", { exact: true }).fill("test-browser-password");
  await page.getByRole("button", { name: "创建账号", exact: true }).click();
  await page.getByRole("link", { name: "服务器设置", exact: true }).click();
  const siteCard = page.locator("[data-slot=card]").filter({ has: page.getByLabel("站点 Base URL") });
  const sttCard = page.locator("[data-slot=card]").filter({ has: page.getByLabel("Soniox API Key", { exact: true }) });
  const siteBox = await siteCard.boundingBox();
  const sttBox = await sttCard.boundingBox();
  expect(Math.abs(siteBox.x - sttBox.x)).toBeLessThan(1);
  expect(Math.abs(siteBox.width - sttBox.width)).toBeLessThan(1);
  expect(sttBox.y).toBeGreaterThanOrEqual(siteBox.y + siteBox.height);
  const fetchModels = () => page.getByRole("button", { name: "获取 LLM 模型", exact: true }).click();
  await fetchModels();
  await expect(page.getByRole("status").filter({ hasText: "已获取 2 个模型" })).toBeVisible();
  await expect(page.getByLabel("搜索模型", { exact: true })).toHaveCount(0);
  await expect(page.getByLabel("可用模型", { exact: true })).toHaveCount(0);
  await page.getByLabel("模型名称", { exact: true }).click();
  await expect(page.getByRole("option")).toHaveCount(2);
  await page.getByRole("option", { name: "alpha-model", exact: true }).click();
  await expect(page.getByLabel("模型名称", { exact: true })).toHaveValue("alpha-model");
  await page.getByLabel("模型名称", { exact: true }).fill("manual-model");
  await page.getByLabel("模型名称", { exact: true }).press("Tab");
  await expect(page.getByLabel("模型名称", { exact: true })).toHaveValue("manual-model");
  await expect(page.getByTestId("settings-save-status")).toHaveText("所有修改已保存");
  await expect(page.getByText("已保存，等待重启生效", { exact: true })).toBeVisible();
  await expect(page.getByLabel("LLM API Key", { exact: true })).toHaveValue("");
  await page.getByLabel("LLM Base URL", { exact: true }).fill(`${remote}/v2`);
  await page.getByLabel("LLM API Key", { exact: true }).fill("browser-model-key");
  await fetchModels();
  await expect(page.getByRole("status").filter({ hasText: "已获取 2 个模型" })).toBeVisible();
  await page.getByLabel("LLM Base URL", { exact: true }).fill(`${remote}/empty`);
  await expect(page.getByRole("option")).toHaveCount(0);
  await fetchModels();
  await expect(page.getByText("服务返回空模型列表，请手动填写模型 ID。", { exact: true })).toBeVisible();
  await expect(page.getByLabel("模型名称", { exact: true })).toHaveValue("manual-model");
  await page.getByLabel("LLM Base URL", { exact: true }).fill(`${remote}/error`);
  await fetchModels();
  await expect(page.locator('[data-slot=alert]').filter({ hasText: '模型服务拒绝访问，请检查 API Key 和权限' })).toBeVisible();
  await expect(page.locator('[data-slot=toast-description]').filter({ hasText: '模型服务拒绝访问，请检查 API Key 和权限' })).toBeVisible();
  await page.locator('[data-slot=toast-close]').click();
  await expect(page.getByText(/private upstream response/)).toHaveCount(0);
  await page.getByLabel("LLM Base URL", { exact: true }).fill(`${remote}/slow`);
  await fetchModels();
  await expect(page.getByRole("button", { name: "正在获取模型…", exact: true })).toBeVisible();
  await page.getByLabel("LLM Base URL", { exact: true }).fill(`${remote}/v2`);
  await fetchModels();
  await expect(page.getByRole("status").filter({ hasText: "已获取 2 个模型" })).toBeVisible();
  await page.getByLabel("模型名称", { exact: true }).click();
  await expect(page.getByRole("option")).toHaveCount(2);
  await expect(page.getByRole("option", { name: "obsolete-model", exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("option", { name: "beta-model", exact: true }).click();
  await expect(page.getByLabel("模型名称", { exact: true })).toHaveValue("beta-model");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByTestId("settings-save-status")).toHaveText("所有修改已保存");
  await page.reload();
  await expect(page.getByLabel("模型名称", { exact: true })).toHaveValue("beta-model");
  expect(errors).toEqual([]);
  console.log("LLM model discovery browser acceptance passed: real HTTP, saved/draft key, input dropdown/manual model, single-column layout, empty/error, stale request, mobile/dark.");
} finally {
  await browser.close();
}
