// Real browser and server/database, without HTTP route mocks.
import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const base = process.env.VOICES_TEST_URL;
const audio = process.env.VOICES_TEST_AUDIO;
const errors = [];
try {
 const adminContext = await browser.newContext();
 const userContext = await browser.newContext();
 const admin = await adminContext.newPage();
 const user = await userContext.newPage();
 for (const p of [admin, user]) p.on('pageerror', e => errors.push(e.message));
 await admin.goto(base);
 await expect(admin.getByText('创建管理员账号', { exact: true })).toBeVisible();
 await admin.getByLabel(/^(用户名或邮箱|邮箱)$/, { exact: true }).fill('alice@example.test');
 await admin.getByLabel('用户名', { exact: true }).fill('Alice');
 await admin.getByLabel('密码', { exact: true }).fill('123456');
 await admin.getByRole('button', { name: '创建账号', exact: true }).click();
 await expect(admin.getByRole('heading', { name: '录音库', exact: true })).toBeVisible();
 await expect(admin.getByRole('link', { name: '账号管理', exact: true })).toBeVisible();
 await user.goto(base);
 await user.getByRole('button', { name: '没有账号？注册', exact: true }).click();
 await user.getByLabel(/^(用户名或邮箱|邮箱)$/, { exact: true }).fill('bob@example.test');
 await user.getByLabel('用户名', { exact: true }).fill('Bob');
 await user.getByLabel('密码', { exact: true }).fill('123456');
 await user.getByRole('button', { name: '创建账号', exact: true }).click();
 await expect(user.getByRole('heading', { name: '录音库', exact: true })).toBeVisible();
 await expect(user.getByRole('link', { name: '账号管理', exact: true })).toHaveCount(0);
 async function upload(page) {
  await page.getByRole('button', { name: '导入录音', exact: true }).first().click();
  await page.getByLabel('选择音频文件').setInputFiles(audio);
  await page.getByRole('button', { name: /开始导入/ }).click();
  await expect(page.getByRole('dialog',{name:'导入录音',exact:true})).toHaveCount(0,{timeout:15000});
 }
 await upload(admin);
 await user.reload();
 await expect(user.getByText('accounts-meeting', { exact: true })).toHaveCount(0);
 await upload(user);
 await user.getByRole('link', { name: '我的账号', exact: true }).click();
 await user.getByLabel('当前密码', { exact: true }).fill('123456');
 await user.getByLabel('新密码', { exact: true }).fill('changed-browser-password');
 await user.getByLabel('确认新密码', { exact: true }).fill('changed-browser-password');
 await user.getByRole('button', { name: '修改密码并退出', exact: true }).click();
 await expect(user.getByLabel(/^(用户名或邮箱|邮箱)$/, { exact: true })).toBeVisible();
 await user.getByLabel(/^(用户名或邮箱|邮箱)$/, { exact: true }).fill('BOB');
 await user.getByLabel('密码', { exact: true }).fill('changed-browser-password');
 await user.getByRole('button', { name: '进入工作台', exact: true }).click();
 await expect(user.getByRole('heading', { name: '我的账号', exact: true })).toBeVisible();
 await admin.getByRole('link', { name: '账号管理', exact: true }).click();
 await expect(admin.getByText('bob@example.test', { exact: true })).toBeVisible();
 await admin.getByRole('switch', { name: '允许创建新账号' }).uncheck();
 await expect(admin.getByRole('switch', { name: '允许创建新账号' })).not.toBeChecked();
 const anonymous = await browser.newPage();
 await anonymous.goto(base);
 await expect(anonymous.getByText('注册已关闭，请使用已有账号登录。')).toBeVisible();
 await user.getByRole('button', { name: '退出登录' }).click();
 await expect(user.getByLabel(/^(用户名或邮箱|邮箱)$/, { exact: true })).toBeVisible();
 expect(errors).toEqual([]);
 console.log('PASS: first admin registration, ordinary registration, isolated uploads, password change/login/logout, registration management');
} finally { await browser.close(); }
